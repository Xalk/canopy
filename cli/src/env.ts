import type { Config } from './config.js';

/** canopy.yaml -> the env vars the container reads (see .env.example). Secrets stay in .env. */
export function configToEnv(cfg: Config): Record<string, string> {
  const env: Record<string, string | undefined> = {
    PROFILE: cfg.profile,
    REPOS: cfg.repos.map((r) => (r.branch ? `${r.repo}#${r.branch}` : r.repo)).join(','),
    VAULT_REPO: cfg.vault,
    WORKDIR: cfg.workdir,
    GIT_NAME: cfg.git?.name,
    GIT_EMAIL: cfg.git?.email,
    TZ: cfg.tz,
    // Always set: the container then configures exactly these servers ("none" = no MCP servers).
    MCP: cfg.mcp.join(',') || 'none',
  };
  return Object.fromEntries(Object.entries(env).filter((e): e is [string, string] => !!e[1]));
}

export function formatEnvFile(env: Record<string, string>): string {
  return (
    '# Generated by canopy from canopy.yaml. Do not edit.\n' +
    Object.entries(env)
      .map(([k, v]) => `${k}=${v}\n`)
      .join('')
  );
}

/** Parse KEY=VALUE lines (comments and blank lines ignored; surrounding quotes stripped). */
export function parseEnvFile(text: string): Record<string, string> {
  const env: Record<string, string> = {};
  for (const line of text.split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=(.*)$/);
    if (m) env[m[1]] = m[2].trim().replace(/^(['"])(.*)\1$/, '$2');
  }
  return env;
}
